-- Programs
insert into public.programs (id, code, title, subtitle, summary, audience, outcomes, track_id, standard_id,
                             level_min, level_max, delivery, url, is_active, sort_order)
select md5('tmh-program-' || h.code)::uuid, h.code, h.title, h.subtitle, h.summary, h.audience, h.outcomes,
       s.track_id, s.id, 0, 2, h.delivery, '/tamohi/programs/' || h.code, true, h.standard_number
from _tmh h
join public.standards s on s.number = h.standard_number and s.tool_version_id = md5('cts-v0.2.1')::uuid
on conflict (code) do update set
  title = excluded.title, subtitle = excluded.subtitle, summary = excluded.summary, audience = excluded.audience,
  outcomes = excluded.outcomes, track_id = excluded.track_id, standard_id = excluded.standard_id,
  level_min = excluded.level_min, level_max = excluded.level_max, delivery = excluded.delivery,
  url = excluded.url, is_active = true, sort_order = excluded.sort_order;

-- Program to indicator mapping (recommendations)
delete from public.program_indicators pi using public.programs p where p.id = pi.program_id and p.code like 'TMH-%';
insert into public.program_indicators (program_id, indicator_id)
select p.id, ind.id from public.programs p join public.indicators ind on ind.standard_id = p.standard_id
where p.code like 'TMH-%';

-- Modules: one per indicator, numbered within the program
insert into public.program_modules (id, program_id, indicator_id, number, title, summary)
select md5('tmh-module-' || ind.id)::uuid, p.id, ind.id,
       row_number() over (partition by p.id order by ind.number)::smallint,
       m.title, split_part(ind.text, '،', 1)
from public.programs p
join public.indicators ind on ind.standard_id = p.standard_id
join _mod m on m.indicator_number = ind.number
where p.code like 'TMH-%'
on conflict (id) do update set title = excluded.title, summary = excluded.summary, number = excluded.number;

-- Lessons: one per item. Kind from what the item asks for:
--   checkpoint = confirm an approval, date or update; template = produce a document, record, plan or report; practice = apply it
insert into public.program_lessons (id, module_id, item_id, number, title, objective, kind, duration_minutes)
select md5('tmh-lesson-' || i.id)::uuid, m.id, i.id,
       row_number() over (partition by m.id order by i.number)::smallint,
       i.text, i.improvement_action, k.kind,
       case k.kind when 'checkpoint' then 10 when 'template' then 25 else 30 end
from public.program_modules m
join public.programs p on p.id = m.program_id and p.code like 'TMH-%'
join public.items i on i.indicator_id = m.indicator_id
cross join lateral (select case
    when i.text ~ '(معتمد|اعتماد|محدث|تحديث|تاريخ)' then 'checkpoint'
    when i.text ~ '(وثيقة|سجل|خطة|تقرير|دليل|سياسة|سياسات|نموذج|قائمة|مصفوفة)' then 'template'
    else 'practice' end as kind) k
on conflict (id) do update set title = excluded.title, objective = excluded.objective, kind = excluded.kind,
  duration_minutes = excluded.duration_minutes, number = excluded.number;

select count(*) filter (where code like 'TMH-%') as programs,
       (select count(*) from public.program_modules) as modules,
       (select count(*) from public.program_lessons) as lessons,
       (select round(sum(duration_minutes) / 60.0) from public.program_lessons) as hours
from public.programs;

commit;
